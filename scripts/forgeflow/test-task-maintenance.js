#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const { ingestFailure, repairFailure, reconcileRepair, revalidateFailure, prepareDraft, readState, recoverMaintenanceLock, main } = require('./task-maintenance');
const store = require('./task-store');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'forgeflow-task-maintenance-'));
const projectDir = path.join(root, '.forgeflow', path.basename(root));
const local = (name) => path.join(projectDir, name);
const relative = (file) => path.relative(root, file);
const git = (args) => execFileSync('git', args, { cwd: root, stdio: 'pipe' });
function writeProposal(name, search, replacement) {
  const file = local(name);
  fs.writeFileSync(file, JSON.stringify({ status: 'proposed', root, finding: { id: name, policy: { proposal_allowed: true } }, operations: [{ op: 'replace', file: 'math.js', search, replace: replacement }], validations_requested: [] }));
  return relative(file);
}
try {
  assert.match(main(['--help']).usage, /validate/);
  git(['init']);
  fs.writeFileSync(path.join(root, 'math.js'), 'module.exports = (a, b) => a - b;\n');
  fs.writeFileSync(path.join(root, 'check.js'), "const assert = require('node:assert/strict'); const add = require('./math'); assert.equal(add(2, 3), 5); assert.equal(add(-2, 3), 1); console.log('behavior passed');\n");
  git(['add', 'math.js', 'check.js']);
  git(['-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-m', 'broken fixture']);
  fs.mkdirSync(projectDir, { recursive: true });
  const failure = spawnSync(process.execPath, ['check.js'], { cwd: root, encoding: 'utf8' });
  assert.equal(failure.status, 1);
  fs.writeFileSync(local('ci.log'), failure.stderr);
  const event = { repository_root: root, run_id: 'fixture-100', attempt: 1, max_attempts: 2, log_file: relative(local('ci.log')), command: [process.execPath, 'check.js'] };
  const classified = ingestFailure(root, event);
  assert.equal(classified.status, 'classified');
  assert.equal(ingestFailure(root, event).deduplicated, true);
  assert.match(fs.readFileSync(path.join(root, classified.digest.path), 'utf8'), /Forgeflow Failure Digest/);
  assert.throws(() => ingestFailure(root, { ...event, command: ['node', 'another.js'] }), /conflicting/);
  assert.throws(() => ingestFailure(root, { ...event, attempt: 3 }), /exhaustion/);
  const otherRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'forgeflow-maintenance-other-'));
  try {
    execFileSync('git', ['init'], { cwd: otherRoot, stdio: 'pipe' });
    assert.throws(() => ingestFailure(root, { ...event, repository_root: otherRoot }), /another repository/);
  } finally { fs.rmSync(otherRoot, { recursive: true, force: true }); }
  assert.throws(() => prepareDraft(root, classified.task_id), /passing repair/);
  fs.writeFileSync(path.join(root, 'new.txt'), 'unrelated edit');
  const goodProposal = writeProposal('good.json', 'a - b', 'a + b');
  assert.throws(() => repairFailure(root, classified.task_id, { proposal_file: goodProposal }), /Source changed/);
  fs.unlinkSync(path.join(root, 'new.txt'));
  const repaired = repairFailure(root, classified.task_id, { proposal_file: goodProposal });
  assert.equal(repaired.status, 'validated');
  assert.equal(spawnSync(process.execPath, ['check.js'], { cwd: root }).status, 0);
  assert.throws(() => repairFailure(root, classified.task_id, { proposal_file: goodProposal }), /already attempted/);
  const draft = prepareDraft(root, classified.task_id);
  assert.equal(draft.remote_written, false);
  assert.match(draft.body, /Validation passed/);
  assert.equal(store.taskView(root, store.readTask(root, classified.task_id)).status, 'complete');
  fs.writeFileSync(path.join(root, 'math.js'), 'module.exports = (a, b) => a - b;\n');
  const crash = ingestFailure(root, { ...event, run_id: 'fixture-crash', max_attempts: 1 });
  repairFailure(root, crash.task_id, { proposal_file: goodProposal });
  const crashState = readState(root, crash.task_id);
  const proofsBefore = store.readTask(root, crash.task_id).evidence.length;
  crashState.status = 'repairing';
  crashState.attempts[0].status = 'pending';
  store.atomicWrite(path.join(projectDir, 'maintenance', `${crash.task_id}.json`), crashState);
  reconcileRepair(root, crash.task_id, { status: 'confirmed', evidence: 'Inspected applied source and saved successful check after interruption.' });
  assert.equal(revalidateFailure(root, crash.task_id).status, 'validated');
  assert.equal(store.readTask(root, crash.task_id).evidence.length, proofsBefore, 'recovery must reuse current proof without rerunning or reapplying');
  assert.equal(prepareDraft(root, crash.task_id).remote_written, false);
  fs.appendFileSync(path.join(root, 'math.js'), '// changed after validation\n');
  assert.throws(() => prepareDraft(root, classified.task_id), /stale/);
  fs.writeFileSync(path.join(root, 'math.js'), 'module.exports = (a, b) => a - b;\n');
  const exhausted = ingestFailure(root, { ...event, run_id: 'fixture-fails', max_attempts: 1 });
  const badProposal = writeProposal('bad.json', 'a - b', 'a * b');
  const failed = repairFailure(root, exhausted.task_id, { proposal_file: badProposal });
  assert.equal(failed.status, 'validation-failed');
  assert.equal(store.readTask(root, exhausted.task_id).evidence.at(-1).status, 'failed');
  assert.throws(() => repairFailure(root, exhausted.task_id, { proposal_file: goodProposal }), /limit exhausted/);
  assert.throws(() => prepareDraft(root, exhausted.task_id), /passing repair/);
  const interrupted = ingestFailure(root, { ...event, run_id: 'fixture-interrupted' });
  const mismatch = writeProposal('mismatch.json', 'text that is absent', 'a + b');
  assert.throws(() => repairFailure(root, interrupted.task_id, { proposal_file: mismatch }), /matched 0/);
  assert.equal(readState(root, interrupted.task_id).status, 'needs-reconciliation');
  assert.throws(() => repairFailure(root, interrupted.task_id, { proposal_file: goodProposal }), /reconciliation/);
  reconcileRepair(root, interrupted.task_id, { status: 'not-performed', evidence: 'Unique replacement search failed before writing; inspected unchanged source.' });
  assert.equal(readState(root, interrupted.task_id).status, 'reconciled');
  const lock = path.join(projectDir, 'maintenance', `${interrupted.task_id}.json.lock`);
  fs.writeFileSync(lock, JSON.stringify({ pid: process.pid }));
  assert.throws(() => recoverMaintenanceLock(root, interrupted.task_id), /still running/);
  fs.unlinkSync(lock);
  fs.writeFileSync(path.join(root, 'math.js'), 'module.exports = (a, b) => a - b;\n');
  const counterPath = relative(local('check-count.txt'));
  fs.writeFileSync(path.join(root, 'interrupt-check.js'), `const fs = require('fs'); const counter = ${JSON.stringify(counterPath)}; const count = fs.existsSync(counter) ? Number(fs.readFileSync(counter)) + 1 : 1; fs.writeFileSync(counter, String(count)); if (count < 3) fs.appendFileSync('math.js', '// validation changed source ' + count + '\\n'); require('./check');\n`);
  const repeated = ingestFailure(root, { ...event, run_id: 'fixture-repeat-interruption', max_attempts: 1, command: [process.execPath, 'interrupt-check.js'] });
  assert.throws(() => repairFailure(root, repeated.task_id, { proposal_file: goodProposal }), /Source changed during validation/);
  const reconciliation = { status: 'confirmed', evidence: 'Inspected applied repair.', check_status: 'confirmed', check_evidence: 'Validation ran and changed a source comment; its output was inspected.' };
  reconcileRepair(root, repeated.task_id, reconciliation);
  assert.throws(() => revalidateFailure(root, repeated.task_id), /Source changed during validation/);
  reconcileRepair(root, repeated.task_id, reconciliation);
  assert.equal(revalidateFailure(root, repeated.task_id).status, 'validated');
  assert.equal(Number(fs.readFileSync(local('check-count.txt'))), 3);
  assert.equal(prepareDraft(root, repeated.task_id).remote_written, false);
  console.log('task maintenance: real failed behavior repaired, current validation drafted, retries and interrupted actions bounded');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
