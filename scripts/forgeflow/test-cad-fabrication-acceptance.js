#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { mesh, stl, parseStl, inspect, sectionAreas, build, verify, validateParameters, hash } = require('../../fixtures/cad-fabrication-acceptance/model');
const parameters = require('../../fixtures/cad-fabrication-acceptance/parameters.json');
const clone = value => JSON.parse(JSON.stringify(value));
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'forgeflow-cad-'));
let defects = 0;
function rejected(label, run, message) {
  assert.throws(run, message, label); defects++;
}
try {
  const artifacts = build(parameters);
  for (const [name, value] of [['frame.stl', artifacts.stl], ['preview.svg', artifacts.preview], ['manifest.json', JSON.stringify(artifacts.manifest)]]) fs.writeFileSync(path.join(temporary, name), value);
  const read = { stl: fs.readFileSync(path.join(temporary, 'frame.stl'), 'utf8'), preview: fs.readFileSync(path.join(temporary, 'preview.svg'), 'utf8'), manifest: JSON.parse(fs.readFileSync(path.join(temporary, 'manifest.json'), 'utf8')) };
  assert.deepEqual(read, artifacts, 'disk artifacts match generated bytes');
  const result = verify(parameters, read);
  assert.equal(result.digital, 'pass');
  for (const key of ['slicer', 'physical', 'overall']) assert.equal(result[key], 'pending', `${key} cannot pass from mesh evidence`);
  assert.deepEqual(result.min, [0, 0, 0]);
  assert.deepEqual(result.max, [80, 60, 8]);
  assert.equal(result.triangles, 32);
  assert.ok(Math.abs(result.volume - 17568) < 1e-7, 'independent literal frame volume');
  assert.deepEqual(build(parameters), artifacts, 'repeat generation deterministic');
  const faces = parseStl(read.stl);
  assert.deepEqual(faces, mesh(parameters));
  for (const z of [1, 4, 7]) assert.deepEqual(sectionAreas(faces, z), [2604, 4800], 'two closed mesh contours with literal areas');
  const clearances = [0, 1].map(i => (parameters.opening[i] - parameters.openingTolerance - parameters.object[i] - parameters.objectTolerance) / 2);
  assert.ok(clearances.every(v => Math.abs(v - 0.7) < 1e-10));
  assert.ok(read.preview.includes(`mesh-sha256:${hash(read.stl)}`));
  assert.equal((read.preview.match(/<polygon /g) || []).length, 96, 'three views from all 32 exported triangles');

  // Valid alternative dimensions and exact plate/clearance boundaries are controls.
  const alternative = { ...clone(parameters), outer: [90, 70], opening: [64, 44], height: 10 };
  assert.equal(verify(alternative, build(alternative)).digital, 'pass');
  const boundary = { ...clone(parameters), openingTolerance: 0.5, objectTolerance: 0.5, placement: [140, 160, 0] };
  assert.equal(verify(boundary, build(boundary)).digital, 'pass');
  assert.deepEqual(sectionAreas(parseStl(build(alternative).stl), 5), [2816, 6300]);

  rejected('wrong declared unit', () => build({ ...parameters, units: 'inch' }), /units/);
  rejected('nominal gap passes but worst-case clearance fails', () => build({ ...parameters, opening: [61.5, 41.5] }), /clearance/);
  rejected('thin wall', () => build({ ...parameters, opening: [79, 59] }), /wall/);
  rejected('plate overflow', () => build({ ...parameters, placement: [140.1, 160, 0] }), /plate/);
  rejected('floating above plate', () => build({ ...parameters, placement: [10, 10, 1] }), /contact/);
  rejected('invalid height', () => build({ ...parameters, height: NaN }), /height/);
  rejected('missing tolerance', () => validateParameters({ ...parameters, objectTolerance: undefined }), /objectTolerance/);
  rejected('open mesh', () => inspect(faces.slice(1)), /open or nonmanifold/);
  const flipped = clone(faces); flipped[0].reverse();
  rejected('one reversed face', () => inspect(flipped), /winding/);
  rejected('inverted solid', () => inspect(clone(faces).map(face => face.reverse())), /inverted/);
  rejected('duplicate face', () => inspect([...faces, faces[0]]), /duplicate/);
  const degenerate = clone(faces); degenerate[0][1] = degenerate[0][0];
  rejected('zero-area triangle', () => inspect(degenerate), /degenerate/);
  const invalid = clone(faces); invalid[0][0][0] = Infinity;
  rejected('nonfinite mesh', () => inspect(invalid), /nonfinite/);
  const extra = clone(faces).map(face => face.map(p => [p[0] + 100, p[1], p[2]]));
  rejected('unexpected separate shell', () => inspect([...faces, ...extra]), /disconnected/);
  rejected('empty export', () => parseStl('solid frame\nendsolid frame\n'), /invalid STL/);
  rejected('nonfinite parsed vertex', () => parseStl(read.stl.replace('vertex 0 0 0', 'vertex NaN 0 0')), /nonfinite/);
  rejected('trailing export corruption', () => parseStl(`${read.stl}garbage`), /invalid STL/);
  rejected('stale parameter identity', () => verify(alternative, read), /identity/);
  rejected('stale generator identity', () => verify(parameters, { ...read, manifest: { ...read.manifest, generator: 'old' } }), /identity/);
  rejected('stale preview', () => verify(parameters, { ...read, preview: build(alternative).preview }), /preview/);
  const scaled = stl(faces.map(face => face.map(p => p.map(v => v * 25.4))));
  rejected('unit conversion in export', () => verify(parameters, { ...read, stl: scaled }), /export differs/);
  const changed = clone(faces); changed[0][0][0] += 1;
  rejected('broken exported geometry', () => verify(parameters, { ...read, stl: stl(changed) }), /open or nonmanifold/);
  rejected('open cross-section', () => sectionAreas(faces.slice(1), 4), /open section/);
  rejected('empty cross-section', () => sectionAreas(faces, 9), /empty section/);
  console.log(`CAD acceptance: 3 clean configurations, 3 mesh sections, ${defects} seeded failures, current STL/preview identity and separate pending slicer/physical status passed`);
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}
